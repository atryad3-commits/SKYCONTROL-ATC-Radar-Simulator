  LANDED_ROLLOUT: ['RUNWAY_EXIT', 'RUNWAY_VACATED', 'LANDED', 'EMERGENCY'],
  RUNWAY_EXIT: ['RUNWAY_VACATED', 'LANDED', 'TAXI', 'EMERGENCY'],
  RUNWAY_VACATED: ['LANDED', 'TAXI', 'EMERGENCY'],
