  ARRIVAL: ['STAR_ENROUTE', 'BASE_VECTOR', 'FINAL_INTERCEPT', 'APPROACH', 'LOCALIZER_ESTABLISHED', 'DESCENT', 'HOLD_SHORT', 'GO_AROUND', 'EMERGENCY'],
  STAR_ENROUTE: ['BASE_VECTOR', 'FINAL_INTERCEPT', 'APPROACH', 'LOCALIZER_ESTABLISHED', 'ARRIVAL', 'GO_AROUND', 'EMERGENCY'],
  BASE_VECTOR: ['FINAL_INTERCEPT', 'APPROACH', 'LOCALIZER_ESTABLISHED', 'STAR_ENROUTE', 'ARRIVAL', 'GO_AROUND', 'EMERGENCY'],
  FINAL_INTERCEPT: ['APPROACH', 'LOCALIZER_ESTABLISHED', 'FINAL', 'BASE_VECTOR', 'GO_AROUND', 'EMERGENCY'],
  APPROACH: ['LOCALIZER_ESTABLISHED', 'FINAL', 'ARRIVAL', 'BASE_VECTOR', 'FINAL_INTERCEPT', 'GO_AROUND', 'EMERGENCY'],
  LOCALIZER_ESTABLISHED: ['FINAL', 'THRESHOLD_CROSSING', 'FLARE', 'GO_AROUND', 'EMERGENCY'],
  FINAL: ['THRESHOLD_CROSSING', 'FLARE', 'GO_AROUND', 'EMERGENCY'],
  THRESHOLD_CROSSING: ['FLARE', 'TOUCHDOWN', 'GO_AROUND', 'EMERGENCY'],
