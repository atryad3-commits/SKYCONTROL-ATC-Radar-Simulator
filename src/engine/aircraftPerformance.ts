  initialSpawnSpeedMaxIAS: number;     // Initial inbound max IAS
  initialDepartureClearanceAglFt: number; // Default initial SID/departure climb AGL

  // Touchdown Limits
  touchdownMaxSinkRateFpm: number;     // Maximum allowable descent rate at touchdown
  touchdownNominalSinkRateFpm: number; // Normal flare touchdown rate

  // Operational Classification & Educational Simulation Scope
  dataSource: 'Manufacturer FCOM / ICAO Doc 8643' | 'Manufacturer POH / ICAO Doc 8643' | 'Educational Simulation Approximate';
