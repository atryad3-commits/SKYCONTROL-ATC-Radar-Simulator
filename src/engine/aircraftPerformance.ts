  accelRateKts_s: number;              // Airborne acceleration rate
  decelRateKts_s: number;              // Airborne deceleration rate
  initialClimbRateFpm: number;         // Initial climb rate off runway up to 1,500 ft AGL
  maxClimbRateFpm: number;             // Maximum continuous climb rate
  normalDescentRateFpm: number;        // Standard descent rate
  maxBankAngleDeg: number;             // Normal flight control bank angle limit

  // Altitude & Spawning Envelopes
  serviceCeilingFt: number;            // Certified aircraft service ceiling
  tmaOperatingCeilingFt: number;       // Practical terminal sector ceiling
  initialSpawnAltMinAglFt: number;     // Realistic TMA arrival lower AGL bound
  initialSpawnAltMaxAglFt: number;     // Realistic TMA arrival upper AGL bound
