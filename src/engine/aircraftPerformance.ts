/** Default fallback performance profile */
const DEFAULT_PERFORMANCE: AircraftPerformance = AIRCRAFT_PERFORMANCE_DATABASE.A320;

/**
 * Retrieves performance specifications for an aircraft type
 */
export function getAircraftPerformance(aircraftType: string): AircraftPerformance {
  const normalized = aircraftType.toUpperCase().trim();
  return AIRCRAFT_PERFORMANCE_DATABASE[normalized] || DEFAULT_PERFORMANCE;
}

/**
 * Computes valid ATC operational bounds (IAS and Altitude MSL) for a given aircraft & field elevation
 */
export function getAircraftOperationalBounds(
  aircraftType: string,
  fieldElevationFt: number = 0
): {
  minSpeedKt: number;
  maxSpeedKt: number;
  minAltitudeFt: number;
  maxAltitudeFt: number;
} {
  const perf = getAircraftPerformance(aircraftType);
  const roundedElev = Math.ceil(fieldElevationFt / 500) * 500;
  const minAltitudeFt = Math.max(1000, roundedElev + 1000);
  const maxAltitudeFt = Math.max(
    minAltitudeFt + 1000,
    Math.min(22000, perf.serviceCeilingFt)
  );
  return {
    minSpeedKt: perf.minAirspeedIAS,
    maxSpeedKt: perf.maxAirspeedIAS,
    minAltitudeFt,
    maxAltitudeFt,
  };
}

/**
 * Returns quick-select speed and altitude presets tailored to the selected aircraft model
 */
export function getAircraftClassPresets(
  aircraftType: string,
  fieldElevationFt: number = 0
): {
  speedPresetsKt: number[];
  altitudePresetsFt: number[];
} {
  const perf = getAircraftPerformance(aircraftType);
  const bounds = getAircraftOperationalBounds(aircraftType, fieldElevationFt);

  let rawSpeeds: number[];
  let rawAltOffsets: number[];

  if (perf.aircraftClass === 'LIGHT_GA') {
    rawSpeeds =
      perf.maxAirspeedIAS >= 165
        ? [95, 115, 135, 160]
        : [80, 95, 110, 125];
    rawAltOffsets = [1500, 2500, 3500, 5000];
  } else if (perf.aircraftClass === 'REGIONAL_TURBOPROP') {
    rawSpeeds = [135, 165, 195, 225];
    rawAltOffsets = [2000, 4000, 6000, 8000];
  } else {
    rawSpeeds = [160, 190, 220, 250];
    rawAltOffsets = [2000, 4000, 6000, 9000];
  }

  const speedPresetsKt = Array.from(
    new Set(
      rawSpeeds.map(s =>
        Math.max(bounds.minSpeedKt, Math.min(bounds.maxSpeedKt, s))
      )
    )
  ).sort((a, b) => a - b);

  const base = Math.ceil(fieldElevationFt / 1000) * 1000;
  const altitudePresetsFt = Array.from(
    new Set(
      rawAltOffsets.map(off =>
        Math.max(bounds.minAltitudeFt, Math.min(bounds.maxAltitudeFt, base + off))
      )
    )
  ).sort((a, b) => a - b);

  return { speedPresetsKt, altitudePresetsFt };
}
